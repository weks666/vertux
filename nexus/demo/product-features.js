export function registerProductFeature(feature, terms = {}) {
 if(!feature?.id||!feature.title||!feature.view||PRODUCT_FEATURES.some(row=>row.id===feature.id))throw new TypeError('Unique feature metadata is required');
 PRODUCT_FEATURES.push(feature);Object.assign(FEATURE_TERMS,terms);
}
const normalized=value=>String(value||'').toLocaleLowerCase('ru').replace(/ё/g,'е').replace(/[^\p{L}\p{N}%/]+/gu,' ').trim();
export function searchProduct(query,{terms=FEATURE_TERMS,catalog=[],pages=[]}={}) {
 const words=normalized(query).split(/\s+/).filter(Boolean);if(!words.length)return[];
 const entries=[
 ...PRODUCT_FEATURES.map(row=>({...row,kind:'Раздел',search:row.keywords})),
 ...Object.entries(terms).map(([id,term])=>({id:'term-'+id,title:term.name,kind:'Термин',view:'glossary',term:id,search:[term.abbr,term.nameEn,term.summary,term.details,term.formula].join(' ')})),
 ...catalog.map(row=>({id:'asset-'+row.instrumentUid,title:[row.ticker,row.name].filter(Boolean).join(' · '),kind:'Инструмент',view:'instruments',target:'catalogSurface',instrumentUid:row.instrumentUid,search:[row.classCode,row.basicAsset,row.sector,row.isin,row.assetType==='future'?'фьючерс':'акция'].join(' ')})),
 ...pages
 ];
 const seen=new Set();
 return entries.map(row=>{const title=normalized(row.title),all=title+' '+normalized(row.search);
  return {...row,score:words.every(word=>all.includes(word))?(title===normalized(query)?100:title.startsWith(normalized(query))?80:words.every(word=>title.includes(word))?60:20)+(row.kind==='Раздел'?10:0):0};
 }).filter(row=>row.score>0).sort((a,b)=>b.score-a.score||a.title.localeCompare(b.title,'ru')).filter(row=>{const key=row.view+'|'+(row.instrumentUid||row.term||row.target||row.title);if(seen.has(key))return false;seen.add(key);return true;}).slice(0,24);
}
